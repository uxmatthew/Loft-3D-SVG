const num = (s, k) => Number((s.match(new RegExp(`\\b${k}="([^"]*)"`)) || [])[1] || 0);
const attr = (s, k) => (s.match(new RegExp(`\\b${k}="([^"]*)"`)) || [])[1];
// Every drawing element as path data, in document order.
function outlines(svg) {
  const out = [];
  for (const [el, name] of svg.matchAll(/<(path|circle|ellipse|rect|line|polyline|polygon)\b[^>]*>/g)) {
    if (attr(el, 'stroke') === 'none') continue; // Tabler's invisible 24×24 frame
    if (name === 'path') out.push(attr(el, 'd'));
    else if (name === 'circle' || name === 'ellipse') {
      const cx = num(el, 'cx'), cy = num(el, 'cy'), rx = num(el, name === 'circle' ? 'r' : 'rx'), ry = name === 'circle' ? rx : num(el, 'ry');
      out.push(`M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0z`);
    } else if (name === 'rect') {
      const x = num(el, 'x'), y = num(el, 'y'), w = num(el, 'width'), h = num(el, 'height'), r = Math.min(num(el, 'rx') || num(el, 'ry'), w / 2, h / 2);
      out.push(r
        ? `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}z`
        : `M${x} ${y}h${w}v${h}h${-w}z`);
    } else if (name === 'line') out.push(`M${num(el, 'x1')} ${num(el, 'y1')}L${num(el, 'x2')} ${num(el, 'y2')}`);
    else out.push(`M${attr(el, 'points').trim().replace(/\s+/g, ' ')}${name === 'polygon' ? 'z' : ''}`);
  }
  return out;
}

const data = [];
for (const lib of libraries) {
  const icons = [];
  for (const [k, name] of lib.names.entries()) {
    const res = await fetch(lib.url(name));
    if (!res.ok) throw new Error(`${lib.name}: ${name} (${res.status})`);
    const svg = await res.text();
    const box = attr(svg, 'viewBox').split(/[\s,]+/).map(Number);
    icons.push({ name, concept: concepts[k], box, paths: outlines(svg) });
  }
  const { url, names, ...meta } = lib;
  data.push({ ...meta, icons });
  console.log(`${lib.name}: ${icons.length} icons`);
}

